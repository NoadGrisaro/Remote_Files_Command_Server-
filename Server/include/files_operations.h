#ifndef FILES_OPERATIONS_H
#define FILES_OPERATIONS_H
/**
 * @brief רושם כותב פעיל עבור קובץ נתון תחת מנעול בלעדי.
 * 
 * בודק האם הקובץ כבר נמצא בשימוש לכתיבה או שהטבלה מלאה.
 * אם הקובץ פנוי, מוסיף אותו לרשימת הכותבים הפעילים באופן thread-safe.
 * 
 * @param[in] path נתיב הקובץ שעליו מבוקשת נעילת כתיבה.
 * 
 * @return 1 אם הנעילה בוצעה בהצלחה, 0 אם הנתיב לא תקין, הקובץ כבר תפוס או שהטבלה מלאה.
 */
int addNewWriter(const char *path);

/**
 * @brief משחרר את נעילת הכתיבה על קובץ ומסיר אותו מרשימת הכותבים.
 * 
 * מאתר את הנתיב ברשימת הכותבים הפעילים ומסיר אותו באופן thread-safe.
 * 
 * @param[in] path נתיב הקובץ לשחרור.
 * 
 * @return 1 אם הקובץ נמצא ושוחרר בהצלחה, 0 אם הנתיב לא תקין או שלא היה נעול.
 */
int releaseWriter(const char *path);

#endif // FILES_OPERATIONS_H